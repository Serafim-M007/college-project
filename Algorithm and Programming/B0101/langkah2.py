# Deklarasi berbagai tipe data dasar python
text = "Hello, World!"  # String
number = 42  # Integer
floating_point = 3.14  # Float
status = False  # Boolean

#Cek tipe data dari setiap variabel
print("\nTipe data dari variabel 'text':", type(text))
print("\nTipe data dari variabel 'number':", type(number))
print("\nTipe data dari variabel 'floating_point':", type(floating_point))
print("\nTipe data dari variabel 'status':", type(status))